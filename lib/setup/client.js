/**
 * 星辰会议室 · 会议准备页 —— 客户端脚本。
 *
 * 纯原生 JS：选类型 → 填参数 → 挑人 → 定主持人 → 开始。
 *
 * 两条硬约束写在这里，因为它们是"能不能开局"的判据：
 *   1. **参会人数必须凑够**（选了几个 AI + 自己是否参加 = 设定的人数）；
 *   2. **必须指定一位主持人**，且主持人从**被邀请的会话**里选 ——
 *      工具校验"调用者必须是主持人"，所以主持人得是个真会话，不能是用户自己。
 *
 * 刻意不用模板字符串（反引号）：这段代码要被塞进 `<script>` 里当字符串用，
 * 少一层转义就少一类事故。中文直接写 —— 页面声明了 UTF-8，跟 `lib/live.js` 同款。
 */

export function clientScript() {
  return [
    '(function(){',
    'var ROUTE=window.__MTG_ROUTE__, MEMBERS=window.__MTG_MEMBERS__||[];',
    'var WOLF_RULES=window.__MTG_RULES__||[];',
    '',
    '// ── 状态 ─────────────────────────────────────────────',
    'var S={kind:null,size:6,speak:500,topic:"",rounds:3,rules:{},members:[],host:null,joinSelf:false,myRole:"",seatOrder:"pick",mySeat:""};',
    'WOLF_RULES.forEach(function(r){S.rules[r.key]=r.on===true});',
    '',
    'function $(id){return document.getElementById(id)}',
    'function esc(s){return String(s==null?"":s).replace(/[&<>"]/g,function(c){',
    '  return {"&":"&amp;","<":"&lt;",">":"&gt;","\\"":"&quot;"}[c]})}',
    'function idx(id){for(var i=0;i<S.members.length;i++){if(S.members[i]===id)return i}return -1}',
    'var SEAT="①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯⑰⑱";',
    'function seatLabel(n){return SEAT.charAt(n)||String(n+1)}',
    '',
    'var toastTimer=null;',
    'function toast(msg){var t=$("toast");t.textContent=msg;t.className="toast show";',
    '  clearTimeout(toastTimer);toastTimer=setTimeout(function(){t.className="toast"},2800)}',
    '',
    'function needAi(){return Math.max(0,S.size-(S.joinSelf?1:0))}',
    '',
    '// ── 选类型 ───────────────────────────────────────────',
    'function choose(kind){',
    '  var wolf=(kind==="werewolf");',
    '  S.kind=kind;',
    '  document.body.setAttribute("data-kind",kind);',
    '  $("step-pick").classList.add("hidden");',
    '  $("step-config").classList.remove("hidden");',
    '  $("cfg-title").textContent=wolf?"🐺 狼人杀 · 开局设定":"📋 普通会议 · 会议设定";',
    '  $("only-meeting").classList.toggle("hidden",wolf);',
    '  $("only-werewolf").classList.toggle("hidden",!wolf);',
    '  $("mark-meeting").classList.toggle("hidden",wolf);',
    '  $("mark-wolf").classList.toggle("hidden",!wolf);',
    '  $("size-stepper").classList.toggle("hidden",wolf);',
    '  $("size-numbar").classList.toggle("hidden",!wolf);',
    '  $("size-note").textContent=wolf',
    '    ?"人数决定板子（几狼几神几民）。法官占一个会话位，但他不算玩家。"',
    '    :"参会人数包含你自己（如果勾了\\u201c我也参加\\u201d）。";',
    '  var lo=wolf?4:2, hi=12;',
    '  if(S.size<lo)S.size=wolf?6:lo;',
    '  if(S.size>hi)S.size=hi;',
    '  var sb=$("size-stepper").querySelectorAll("button");',
    '  for(var i=0;i<sb.length;i++){sb[i].dataset.min=lo;sb[i].dataset.max=hi}',
    '  renderAll();',
    '  window.scrollTo({top:0,behavior:"smooth"});',
    '}',
    '',
    'function back(){',
    '  $("step-config").classList.add("hidden");',
    '  $("step-pick").classList.remove("hidden");',
    '  $("tag-kind").className="tag";',
    '  $("tag-kind").textContent="未选择";',
    '  S.kind=null;',
    '  document.body.removeAttribute("data-kind");',
    '}',
    '',
    '// ── 重绘 ─────────────────────────────────────────────',
    'function renderAll(){',
    '  if(S.kind===null)return;',
    '  $("val-size").textContent=S.size;',
    '  $("val-rounds").textContent=S.rounds;',
    '  $("val-speak").textContent=S.speak+" 字";',
    '  var nb=document.querySelectorAll(".numbar button");',
    '  for(var i=0;i<nb.length;i++){nb[i].setAttribute("aria-pressed",String(Number(nb[i].dataset.n)===S.size))}',
    '  var need=needAi();',
    '  var pr=$("pick-progress");',
    '  pr.textContent="已选 "+S.members.length+" / 需要 "+need;',
    '  pr.className="tag"+((need>0&&S.members.length===need)?" on":"");',
    '  renderRoster();',
    '  var ok=(need>0&&S.members.length===need&&S.host!==null);',
    '  $("start").disabled=!ok;',
    '  $("start-why").textContent=ok?"":whyNot(need);',
    '}',
    '',
    'function whyNot(need){',
    '  if(MEMBERS.length===0)return "名册是空的：没有可邀请的会话，先另开几个对话再来";',
    '  if(S.members.length<need)return "还差 "+(need-S.members.length)+" 位";',
    '  if(S.members.length>need)return "多了 "+(S.members.length-need)+" 位";',
    '  if(S.host===null)return "还没定主持人（点名单右边的圆点）";',
    '  return "";',
    '}',
    '',
    'function renderRoster(){',
    '  var box=$("roster");',
    '  if(MEMBERS.length===0){box.innerHTML="<div class=\\"empty\\">没有可邀请的会话。</div>";return}',
    '  var html="";',
    '  for(var i=0;i<MEMBERS.length;i++){',
    '    var m=MEMBERS[i], at=idx(m.sessionId), on=at>=0, isHost=(S.host===m.sessionId);',
    '    html+="<div class=\\"roster-item"+(on?" on":"")+(isHost?" hostpick":"")+"\\" data-id=\\""+esc(m.sessionId)+"\\">";',
    '    html+="<div class=\\"seat\\">"+(on?seatLabel(at):"·")+"</div>";',
    '    html+="<div class=\\"roster-main\\"><div class=\\"roster-name\\">"+esc(m.title||m.sessionId)+"</div>";',
    '    html+="<div class=\\"roster-meta\\">"+esc(m.cwd||"")+(m.weight?" · "+esc(m.weight):"")+"</div></div>";',
    '    if(isHost)html+="<span class=\\"roster-flag host\\">主持</span>";',
    '    html+="<div class=\\"radio-dot\\" title=\\"设为/取消主持人\\"></div>";',
    '    html+="</div>";',
    '  }',
    '  box.innerHTML=html;',
    '}',
    '',
    '// 名单点击：点名字＝选中/取消；点右边圆点＝设为主持人',
    'function onRosterClick(e){',
    '  var row=e.target.closest?e.target.closest(".roster-item"):null;',
    '  if(!row)return;',
    '  var id=row.dataset.id;',
    '  if(e.target.closest(".radio-dot")){',
    '    var wasHost=(S.host===id);',
    '    S.host=wasHost?null:id;',
    '    // 主持人不占参会名额：一人不能既当主持又当参会者（工具那层也这么校验），',
    '    // 所以设成主持人的同时，把他从参会名单里摘掉。',
    '    if(!wasHost){',
    '      var at2=idx(id);',
    '      if(at2>=0){S.members.splice(at2,1);toast("主持人不用再占参会名额，已从名单里摘下")}',
    '    }',
    '    renderAll();return;',
    '  }',
    '  var at=idx(id);',
    '  if(at>=0){',
    '    S.members.splice(at,1);',
    '    if(S.host===id)S.host=null;',
    '  }else{',
    '    if(S.members.length>=needAi()){toast("名额满了，想换人先取消一个");return}',
    '    // 主持人和玩家互斥。先点主持再点玩家会撞上这里 —— 之前漏了这个判断，',
    '    // 结果同一个人既拿警徽又坐座位（2026-10-19 哥哥实测抓到）。',
    '    if(S.host===id){S.host=null;toast("他本来在当主持人，已经撤下来了 —— 记得重新点一个")}',
    '    S.members.push(id);',
    '  }',
    '  renderAll();',
    '}',
    '',
    '// ── 开局 ─────────────────────────────────────────────',
    'function start(){',
    '  var btn=$("start");',
    '  btn.disabled=true;btn.textContent="正在开局…";',
    '  var body={kind:S.kind,size:S.size,speakLimit:S.speak,rules:S.rules,',
    '    members:S.members,host:S.host,joinSelf:S.joinSelf,topic:S.topic,rounds:S.rounds,',
    '    myRole:S.joinSelf?S.myRole:"",seatOrder:S.seatOrder,mySeat:S.joinSelf?S.mySeat:""};',
    '  fetch(ROUTE+"/api/setup/start",{method:"POST",headers:{"Content-Type":"application/json"},',
    '    body:JSON.stringify(body)})',
    '  .then(function(r){return r.json()})',
    '  .then(function(res){',
    '    if(!res||!res.ok){',
    '      toast((res&&res.error)||"开局失败");',
    '      btn.disabled=false;btn.textContent="开始";',
    '      return;',
    '    }',
    '    var box=$("result");',
    '    box.className="result show";',
    '    box.innerHTML="<h3>"+(S.kind==="werewolf"?"🌒 已经开局":"✅ 会议已开房")+"</h3>"',
    '      +"<p>房间号："+esc(res.roomId)+"</p>"',
    '      +"<p>主持人："+esc(res.hostTitle||"")+"</p>"',
    '      +"<p>参会："+res.memberCount+" 位"+(res.joinSelf?"（含你自己）":"")+"</p>"',
    '      +(res.liveUrl?"<a class=\\"btn btn-primary\\" href=\\""+esc(res.liveUrl)+"\\" target=\\"_blank\\" rel=\\"noreferrer\\">打开会场实况</a>":"");',
    '    box.scrollIntoView({behavior:"smooth",block:"center"});',
    '    btn.textContent="已开局";',
    '  })',
    '  .catch(function(err){',
    '    toast("请求失败："+(err&&err.message?err.message:String(err)));',
    '    btn.disabled=false;btn.textContent="开始";',
    '  });',
    '}',
    '',
    '// ── 事件绑定（委托，一次搞定） ───────────────────────',
    'document.addEventListener("click",function(e){',
    '  if(!e.target.closest)return;',
    '  var pickCard=e.target.closest(".pick");',
    '  if(pickCard){choose(pickCard.dataset.kind);return}',
    '  var n=e.target.closest(".numbar button");',
    '  if(n){S.size=Number(n.dataset.n);trimToSize();refreshSeats();renderAll();return}',
    '  var st=e.target.closest(".stepper button");',
    '  if(st){',
    '    var v=Number(S[st.dataset.field])+Number(st.dataset.delta);',
    '    var lo=Number(st.dataset.min),hi=Number(st.dataset.max);',
    '    if(v<lo)v=lo;if(v>hi)v=hi;',
    '    S[st.dataset.field]=v;trimToSize();refreshSeats();renderAll();return;',
    '  }',
    '  var rule=e.target.closest(".rule");',
    '  if(rule){var k=rule.dataset.key;S.rules[k]=!S.rules[k];',
    '    rule.setAttribute("aria-pressed",String(S.rules[k]));return}',
    '  if(e.target.closest("#roster")){onRosterClick(e);return}',
    '  if(e.target.closest("#back")){back();return}',
    '  if(e.target.closest("#start")){start();return}',
    '});',
    '',
    'function trimToSize(){',
    '  while(S.members.length>needAi())S.members.pop();',
    '}',
    '',
    'document.addEventListener("input",function(e){',
    '  if(e.target.id==="speak"){S.speak=Number(e.target.value);$("val-speak").textContent=S.speak+" 字";return}',
    '  if(e.target.id==="topic"){S.topic=e.target.value;return}',
    '});',
    '',
    'var join=$("joinSelf");',
    'if(join){join.addEventListener("change",function(){',
    '  S.joinSelf=join.checked;',
    '  var wrap=$("myrole-wrap");',
    '  if(wrap)wrap.classList.toggle("hidden",!S.joinSelf);',
    '  trimToSize();refreshSeats();renderAll();',
    '})}',
    'var roleSel=$("myRole");',
    'if(roleSel){roleSel.addEventListener("change",function(){S.myRole=roleSel.value})}',
    // 座位顺序：点选先后 / 随机洗牌
    'var orderSel=$("seatOrder");',
    'if(orderSel){orderSel.addEventListener("change",function(){S.seatOrder=orderSel.value;renderAll()})}',
    // 「我坐第几号」的选项随人数变化重填（人数少时别留着 18 号这种空选项）
    'function refreshSeats(){',
    '  var sel=$("mySeat");if(!sel)return;',
    '  var n=S.size||6,before=S.mySeat;',
    '  var html="<option value=\\"\\">随机</option>";',
    '  for(var i=1;i<=n;i++)html+="<option value=\\""+i+"\\">"+i+" 号</option>";',
    '  sel.innerHTML=html;',
    '  if(before&&Number(before)<=n){sel.value=String(before)}else{S.mySeat="";sel.value=""}',
    '}',
    'var seatSel=$("mySeat");',
    'if(seatSel){seatSel.addEventListener("change",function(){S.mySeat=seatSel.value})}',
    'refreshSeats();',
    '',
    'renderAll();',
    '})();',
  ].join('\n');
}
